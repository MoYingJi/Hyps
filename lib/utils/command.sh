#!/hint/bash

[[ -n "${__UTILS_COMMAND_SH_LOADED:-}" ]] && return 0
__UTILS_COMMAND_SH_LOADED=1

#shellcheck source=../core/log.sh
source "$SCRIPT_DIR/core/log.sh"

#shellcheck source=string.sh
source "$SCRIPT_DIR/utils/string.sh"

command_exists() {
    command -v "$1" >/dev/null 2>&1
}

print_bash_script_header() {
    echo "#!/usr/bin/env bash"
    echo "# Auto-generated by Hyps"
    echo ""
}

pack_declare() {
    declare -p | grep -v '^declare -[a-zA-Z]*r'
    declare -f
}

ensure_executable() {
    local file="$1"
    local module="${2:-utils}"

    if [ ! -x "$file" ]; then
        chmod +x "$file"
    fi

    if [ ! -x "$file" ]; then
        die 1 "$module" "文件 '$file' 不可执行！请手动设置可执行权限！"
    fi
}

sudo_request() {
    local why="$1"
    shift

    local quoted_args
    quoted_args="$(quote_args "$@")"

    {
        echo "[Hyps] [sudo 请求] $why"
        echo "[Hyps] # $quoted_args"
    } >&2

    if [ ! -t 0 ] || isy "$HYPS_FORCE_SUDO_NOTIFY" = "1"; then
        if command_exists notify-send; then
            notify-send \
                --app-name "Hyps" \
                "sudo 请求" \
                $"$why\n请注意查看终端或提权弹窗\n\n# $quoted_args"
        else
            log_warn utils "无法发送 sudo 请求通知给用户"
        fi
    fi

    if command_exists sudo && [ -t 0 ]; then
        # 有 sudo 命令，有终端
        sudo -- "$@"
        return "$?"
    elif command -v pkexec >/dev/null 2>&1 && { [ -n "${DISPLAY:-}" ] || [ -n "${WAYLAND_DISPLAY:-}" ]; }; then
        # 有 pkexec 命令，有显示环境
        log_debug utils "使用 pkexec 获取管理员权限"
        pkexec "$@"
        return "$?"
    else
        die 1 utils "无法获取管理员权限"
        return 1
    fi
}

run_and_log() {
    local level="$1"
    local module="$2"
    local prompt="$3"
    shift 3

    [ -z "$prompt" ] && prompt="执行命令"
    log "$level" "$module" "$prompt: $(quote_args "$@")"
    "$@"
}
